"use strict";

const { isDeepStrictEqual } = require("node:util");
const { expandReference } = require("./pack-legal-references");
const { createBrowserReferenceDecoder } = require("./browser-reference-decoder");

const REFERENCE_FIELDS = { t: "text", c: "continuation", h: "heading", p: "preamble", s: "sourceCredit", x: "x", a: "authority", o: "source" };
const BUILD_METADATA_FIELDS = [
  "generatedReferences", "suppressedSelfReferences", "suppressedSelfReferencesByRule", "suppressedSelfReferencesByFamily",
  "generatedAtBuild", "runtimeNetworkForPreviews", "policySchemaVersion", "policyReviewedAt", "policyScopes",
  "embeddedResolverVersion", "embeddedCandidates", "embeddedResolvedReferences", "embeddedIssues",
  "houseEditorialCitationCorrections", "houseSourceEditorialCitationCorrections", "sourceBracketCitationCorrections",
  "houseTruncatedCitationCorrections", "historicalHouseCitationCorrections", "historicalReviewedReferences", "rules"
];
// These suffixes are already regenerated by the unchanged destination decoders.
// A candidate is still retained unless both decoders reproduce every field.
const REGENERATED_NOTICES = [
  "The official citation link locates the printed page within its containing Statutes at Large document.",
  "The official link searches GovInfo for this Public Law. A verified direct archive is not available here; the slip-law collection begins with the 104th Congress."
];

function trimTarget(parts) {
  while (parts.at(-1) === "" || parts.at(-1) === "0") parts.pop();
  return parts.join("|");
}

function projectReferenceTargets(packing, uses) {
  if (!Array.isArray(packing?.legalTargets)) return;
  let browserDecode;
  const nodeDecode = (target, text) => expandReference([1, 0, text.length, 0], text, [], null, [target]);
  for (const [index, texts] of uses) {
    const original = packing.legalTargets[index];
    if (typeof original !== "string") continue;
    const parts = original.split("|");
    if (!parts[18] || parts[18] === "0") continue;
    const reduced = [...parts];
    reduced[18] = "";
    const candidates = [trimTarget([...reduced])];
    const suffix = REGENERATED_NOTICES.find(notice => parts[15] === notice || parts[15]?.endsWith(` ${notice}`));
    if (suffix) {
      reduced[15] = parts[15] === suffix ? "" : parts[15].slice(0, -suffix.length - 1);
      candidates.push(trimTarget(reduced));
    }
    browserDecode ||= createBrowserReferenceDecoder();
    const candidate = candidates.find(target => texts.every(text =>
      isDeepStrictEqual(nodeDecode(original, text), nodeDecode(target, text)) &&
      isDeepStrictEqual(browserDecode(original, text), browserDecode(target, text))));
    if (candidate !== undefined) packing.legalTargets[index] = candidate;
  }
}

// Preserve the full evidence in the canonical build input; the reader only
// needs the resolved citation targets and spans, not the resolver's audit.
function prepareDeliveryCorpus(source) {
  const corpus = structuredClone(source);
  // The canonical build retains provenance; the reader keeps legal text,
  // displayed warnings, destinations, source currency and cache revision flags.
  for (const target of Object.values(corpus.uscHierarchyLinks?.targets || {})) delete target.heading;
  if (Array.isArray(corpus.policyManual?.catalog)) corpus.policyManual.catalog = [];
  if (Array.isArray(corpus.forms)) corpus.forms = [];
  for (const key of ["groupSources", "coverage", "sourceManifest", "reviewedSourceManifest", "additionalReviewedSourceManifests"]) if (corpus.historicalUsc) delete corpus.historicalUsc[key];
  if (corpus.historicalIna) delete corpus.historicalIna.sourceManifest;
  if (corpus.cfr) delete corpus.cfr.structureSources;
  for (const key of ["inaVerification", "glossaryVerification"]) if (corpus.definitions) delete corpus.definitions[key];
  for (const section of corpus.title8?.sections || []) {
    for (const key of ["sourceArtifact", "sourceSha256", "unitsSha256", "sourceCapturedAt", "transcriptionPolicy", "transcriptionCorrections", "amendmentReview", "headingEvidence", "headingOrigin", "referenceCorrections", "sourcePdfPages", "sourceFile", "pdfPages", "sourceCaptureStatus", "sourceAccessedAt"]) if (section.historical) delete section.historical[key];
  }
  // These two metadata objects have specific runtime currency/migration uses.
  for (const [field, keep] of [["referenceMetadata", "capturedAt"], ["houseFootnoteMetadata", "noteLayoutRevision"]]) {
    for (const key of Object.keys(corpus.title8?.[field] || {})) if (key !== keep) delete corpus.title8[field][key];
  }
  if (Array.isArray(corpus.historicalLocatorCorrections)) {
    corpus.historicalLocatorCorrections = corpus.historicalLocatorCorrections.filter(row => row.kind !== "usc");
    for (const row of corpus.historicalLocatorCorrections) for (const key of ["review", "reason", "sourceSha256"]) delete row[key];
  }
  delete corpus.legalReferenceAudit;
  delete corpus.legalReferenceEvidence;
  // Browser updates regenerate CFR fields only. Keep every CFR guard and all
  // unknown future source kinds; canonical builds retain the complete manifest.
  if (Array.isArray(corpus.legalReferenceExceptions?.exceptions)) {
    corpus.legalReferenceExceptions.exceptions = corpus.legalReferenceExceptions.exceptions.filter(exception => !String(exception.sourceId || "").startsWith("usc-"));
  }
  for (const key of BUILD_METADATA_FIELDS) if (corpus.legalReferenceMetadata) delete corpus.legalReferenceMetadata[key];
  for (const key of ["sources", "references", "hydratedAtRuntime"]) if (corpus.legalReferencePacking) delete corpus.legalReferencePacking[key];
  const targetUses = new Map();
  function visit(value) {
    if (!value || typeof value !== "object") return;
    if (value._lr) for (const [key, refs] of Object.entries(value._lr)) {
      const rows = typeof refs === "string" ? refs.split(";").map(row => row.split(",").map(Number)) : refs;
      const stripped = rows.map(row => Array.isArray(row) && row[0] === 1 ? row.slice(0, 4) : row);
      value._lr[key] = typeof refs === "string" ? stripped.map(row => row.join(",")).join(";") : stripped;
      let previousEnd = 0;
      for (const row of stripped) {
        if (!Array.isArray(row)) continue;
        const start = previousEnd + Number(row[1] || 0), end = start + Number(row[2] || 0);
        previousEnd = end;
        if (row[0] !== 1 || !REFERENCE_FIELDS[key]) continue;
        if (!targetUses.has(row[3])) targetUses.set(row[3], []);
        targetUses.get(row[3]).push(String(value[REFERENCE_FIELDS[key]] || "").slice(start, end));
      }
    }
    Object.values(value).forEach(visit);
  }
  visit(corpus);
  projectReferenceTargets(corpus.legalReferencePacking, targetUses);
  return corpus;
}

module.exports = { prepareDeliveryCorpus };
